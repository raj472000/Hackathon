def _fmt(v: Any, unit: str = "") -> str:
    f = _num(v)
    if f is None:
        return "n/a"
    return f"{f:,.2f}{unit}"


def deterministic_answer(question: str, plan: AskPlan, ev: list[dict[str, Any]], table: list[dict[str, Any]]) -> AskAnswer:
    pts: list[AnswerPoint] = []
    caveats: list[str] = []
    for e in ev:
        d = e["data"]
        if e["kind"] == "quote" and d:
            src = "live" if e["live"] else f"stored close of {e['as_of']}"
            pts.append(AnswerPoint(text=f"{e['title'].split()[0]}: last price INR {_fmt(d.get('last_price'))}"
                                        f" ({_fmt(d.get('change_pct'), '%')} on the day, {src}).", evidence_ids=[e["id"]]))
        elif e["kind"] == "metrics" and d:
            bits = [f"{METRIC_CATALOG[k]['label']} {_fmt(d[k], '%' if METRIC_CATALOG[k]['unit'] == 'pct' else '')}"
                    for k in ("return_3m", "rel_strength_6m", "volatility_252d", "pe", "roce", "overall_score") if k in d]
            if bits:
                pts.append(AnswerPoint(text=f"{e['title'].split()[0]}: " + "; ".join(bits) + ".", evidence_ids=[e["id"]]))
        elif e["kind"] == "screen":
            top = ", ".join(str(r["symbol"]) for r in d.get("top", [])[:5])
            pts.append(AnswerPoint(text=f"{d.get('matched', 0)} of {d.get('universe', 0)} instruments match"
                                        + (f"; leading names: {top}." if top else "."), evidence_ids=[e["id"]]))
        elif e["kind"] == "rotation" and d:
            lead = [k for k, v in d["sectors"].items() if v.get("quadrant") == "leading"]
            imp = [k for k, v in d["sectors"].items() if v.get("quadrant") == "improving"]
            pts.append(AnswerPoint(text=f"Leading sectors: {', '.join(lead) or 'none'}; improving: {', '.join(imp) or 'none'}.",
                                   evidence_ids=[e["id"]]))
        elif e["kind"] == "movers_window" and d.get("top"):
            word = "rose most" if d["direction"] == "gainers" else "fell most"
            pts.append(AnswerPoint(
                text=f"Over the last {d['sessions']} sessions these {word}: "
                     + ", ".join(f"{x['symbol']} {_fmt(x['change_pct'], '%')}" for x in d["top"][:5])
                     + f" (of {d['ranked']} ranked).", evidence_ids=[e["id"]]))
        elif e["kind"] == "movers" and d.get("best_1w"):
            pts.append(AnswerPoint(text="Best 1-week returns: " + ", ".join(f"{x['symbol']} {_fmt(x['return_1w'], '%')}" for x in d["best_1w"][:3]) + ".",
                                   evidence_ids=[e["id"]]))
        elif e["kind"] == "movers":
            pts.append(AnswerPoint(text="Live market movers were retrieved from NSE; see the table of sources.", evidence_ids=[e["id"]]))
        if e.get("note"):
            caveats.append(e["note"])
    if plan.intent == "unknown":
        answer = ("I could not match this question to instruments, screen conditions, sectors or the market overview. "
                  "Try naming a symbol (for example INFY), a condition (low volatility, ROCE above 15, momentum) or a sector.")
    elif not pts:
        answer = "No data is available for this question yet. Run a data refresh from the Data status page."
    else:
        answer = " ".join(p.text for p in pts[:4])
    return AskAnswer(answer=answer[:1200], points=pts[:8], caveats=list(dict.fromkeys(caveats))[:5])


def validate_citations(a: AskAnswer, ev: list[dict[str, Any]]) -> tuple[AskAnswer, list[str]]:
    ids = {e["id"] for e in ev}
    dropped: list[str] = []
    keep = []
    for p in a.points:
        bad = [x for x in p.evidence_ids if x not in ids]
        if bad or not p.evidence_ids:
            dropped.append(p.text[:120])
            continue
        keep.append(p)
    return a.model_copy(update={"points": keep}), dropped


async def ask(c: Container, s: AsyncSession, question: str) -> dict[str, Any]:
    started = datetime.now(UTC)
    insts = await _universe(s)
    raw_plan, plan_source, plan_reason = await make_plan(c, question, insts)
    if plan_source == "llm":
        raw_plan, extra = keep_named_symbols(raw_plan, question, insts)
    else:
        extra = []
    plan, notes = sanitize_plan(raw_plan, insts)
    notes = [*extra, *notes]
    freshness = await ensure_fresh_prices(c, s) if plan.intent != "unknown" else None
    ev, table = await gather(c, s, plan, insts)
    answer_source, answer_reason = "rules", plan_reason
    dropped: list[str] = []
    answer: AskAnswer | None = None
    if c.llm.available and plan.intent != "unknown":
        try:
            user = json.dumps({"question": question, "evidence": ev}, default=str)
            answer, dropped = validate_citations(await c.llm.complete_validated(ANSWER_SYSTEM, user, AskAnswer), ev)
            answer_source, answer_reason = "llm", None
        except LLMError as e:
            answer_reason = str(e)[:300]
    if answer is None:
        answer = deterministic_answer(question, plan, ev, table)
    live = sum(1 for e in ev if e["live"])
    stored = sum(1 for e in ev if not e["live"] and e["source"] != "unavailable")
    return {
        "question": question, "version": VERSION, "asked_at": started.isoformat(),
        "plan": {**plan.model_dump(), "filters_described": [Filter(**f.model_dump()).describe() for f in plan.filters]},
        "plan_source": plan_source, "plan_notes": notes,
        "answer": answer.model_dump(), "answer_source": answer_source,
        "llm": {"used": plan_source == "llm" or answer_source == "llm", "model_id": c.llm.model_id,
                "reason_not_used": answer_reason if answer_source != "llm" else None, "uncited_points_removed": dropped},
        "evidence": ev, "table": table if plan.intent != "movers" else [], "movers": table if plan.intent == "movers" else [],
        "data_sources": {"live_mcp": live, "system_db": stored}, "data_refresh": freshness,
        "llm_disclaimer": LLM_DISCLAIMER if answer_source == "llm" else None,
        "disclaimer": "Research output, not investment advice. Live MCP data is delayed per NSE terms.",
    }
