"""Ask the market: a question in plain language, answered from live MCP data with the database as fallback.

Flow:
1. Interpret the question into a validated `AskPlan` (instruments, screen filters, sectors). The
   configured LLM proposes the plan; if it is unavailable the deterministic rules interpreter does.
   Every symbol is resolved against the instrument master and every filter against the metric
   catalog, so nothing the model writes is executed or trusted unchecked.
2. Gather evidence. Quotes and market indices are fetched live from the MCP connectors; when a
   connector fails, the latest stored values from the system database are used and labelled with
   their as-of date. Screens and computed metrics always come from the database (they are computed
   deterministically from ingested MCP data).
3. Answer. The LLM writes a short answer that may cite only evidence ids it was given; citations
   are checked. Without the model, a deterministic summary of the same evidence is returned.
"""

