import { expect, test, type Page } from '@playwright/test'

// Opt-in checks against a LIVE stack (real NSE MCP data, NSE filings, OpenRouter model, Kite MCP):
//   E2E_LIVE=1 E2E_BASE_URL=http://127.0.0.1:5175 npx playwright test e2e/live-proof.spec.ts --project=desktop
// They read data, ask questions and generate reports (a few cents of model usage). Screenshots go to
// ../analysis/proof/live-*.png.
test.skip(!process.env.E2E_LIVE, 'live stack only')
test.setTimeout(240_000)
const SHOTS = '../analysis/proof'

async function skipBrokerPrompt(page: Page) {
  await page.addInitScript(() => sessionStorage.setItem('broker-login-dismissed', '1'))
}

test('live: overview, ask, themes with members, AI filter', async ({ page }) => {
  await skipBrokerPrompt(page)
  const t0 = Date.now()
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Ask the market' })).toBeVisible()
  await expect(page.getByText('Live data')).toBeVisible()
  expect(Date.now() - t0).toBeLessThan(10_000)
  await page.getByLabel('Your question').fill('How is ICICIBANK doing?')
  await page.getByTestId('ask-submit').click()
  await expect(page.getByTestId('evidence-Q1')).toBeVisible({ timeout: 60_000 })
  await page.screenshot({ path: `${SHOTS}/live-01-ask-icicibank.png`, fullPage: true })

  await page.goto('/themes')
  const momentum = page.locator('li').filter({ has: page.getByRole('link', { name: 'Price momentum', exact: true }) })
  await expect(momentum).toContainText(/\d+ members/)
  await page.screenshot({ path: `${SHOTS}/live-02-themes.png` })
})

test('live: bullish over the last 3 days is answered by the model with ranked moves and a reliability note', async ({ page }) => {
  await skipBrokerPrompt(page)
  await page.goto('/')
  await page.getByLabel('Your question').fill('strong bullish stocks in last 3 days')
  await page.getByTestId('ask-submit').click()
  await expect(page.getByTestId('ask-movers')).toBeVisible({ timeout: 120_000 })
  await expect(page.getByTestId('ask-llm-disclaimer')).toContainText('generated by a language model')
  await expect(page.getByTestId('ask-answer')).not.toContainText('does not show')
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: `${SHOTS}/live-05-ask-bullish-3-days.png`, fullPage: true })
})

test('live: ABB has fundamentals and valuation pillars from NSE filings', async ({ page }) => {
  await skipBrokerPrompt(page)
  await page.goto('/instrument/NSE:ABB')
  const fund = page.locator('div,li').filter({ hasText: /^Fundamentals and financial quality/ }).last()
  await expect(page.getByText(/Fundamentals and financial quality/).first()).toBeVisible({ timeout: 30_000 })
  await expect(page.getByText(/0\/8 metrics/)).toHaveCount(0)
  await expect(page.getByText(/0\/5 metrics/)).toHaveCount(0)
  await expect(page.getByText(/Incomplete: insufficient coverage for fundamentals/)).toHaveCount(0)
  void fund
  await page.getByText('Research score').first().scrollIntoViewIfNeeded()
  await page.screenshot({ path: `${SHOTS}/live-06-abb-pillars.png`, fullPage: true })
})

test('live: rotation plots every sector and the tail slider works', async ({ page }) => {
  await skipBrokerPrompt(page)
  await page.goto('/rotation')
  const cov = page.getByText(/\d+ of \d+ sectors plotted/)
  await expect(cov).toBeVisible({ timeout: 30_000 })
  const [plotted, total] = ((await cov.textContent()) ?? '').match(/\d+/g)!.map(Number)
  expect(plotted).toBe(total)
  await page.getByTestId('rrg-tail').fill('3')
  expect((await page.locator('svg polyline').first().getAttribute('points'))!.trim().split(/\s+/).length).toBe(3)
  await page.screenshot({ path: `${SHOTS}/live-07-rotation-all-sectors-tail-3.png`, fullPage: true })
})

test('live: research board is written by the model, not the rule-based fallback', async ({ page }) => {
  await skipBrokerPrompt(page)
  await page.goto('/research/NSE:TCS')
  const regen = page.getByRole('button', { name: /Regenerate|Generate research/ })
  const [res] = await Promise.all([
    page.waitForResponse((r) => r.url().includes('/research') && r.request().method() === 'POST', { timeout: 180_000 }),
    regen.first().click(),
  ])
  const body = await res.json()
  expect(body.mode).toBe('llm')
  expect(body.llm.reason ?? '').not.toContain('schema validation')
  await expect(page.getByText(/Written by .* from the evidence below/)).toBeVisible({ timeout: 30_000 })
  await expect(page.getByText('Rule-based summary, no language model')).toHaveCount(0)
  await expect(page.getByText(/failed schema validation/)).toHaveCount(0)
  await page.screenshot({ path: `${SHOTS}/live-08-research-tcs-llm.png`, fullPage: true })
})

